"""
Generates BIOFACQUIMStereoSmilesReference.tsv, the reference data of the BIOFACQUIM check in ChemUtilStereoSmilesTest.

For every molecule of the BIOFACQUIM data set in Tutorial/biofacquim-06-2025.sdf, the RDKit canonical isomeric SMILES
(legacy stereo perception, the default of RDKit 2026.09.1) and three writings with random atom orders are given. The
writings are Kekule SMILES, like the structures MORTAR creates when it imports SD files (kekulized, no aromaticity
perception); since the unique SMILES of a Kekule structure depends on its Kekule form, the test perceives
aromaticity on both sides before comparing. The record column is the 1-based position of the molecule in the SD file.

A writing is only used if RDKit itself parses it back to the canonical SMILES of the molecule. This is not the case
for some writings of record 456 (an inositol): RDKit writes a different stereoisomer for some atom orders. Such
writings are discarded and replaced by further random writings; their number is given in the second comment line.

Usage (RDKit 2026.09.1), from the repository root:
    python -I src/test/resources/de/unijena/cheminf/mortar/model/util/generate_biofacquim_stereo_reference.py \
        Tutorial/biofacquim-06-2025.sdf > src/test/resources/de/unijena/cheminf/mortar/model/util/BIOFACQUIMStereoSmilesReference.tsv
"""

import random
import sys

from rdkit import Chem, RDLogger, rdBase

RDLogger.DisableLog("rdApp.*")

WRITINGS_PER_MOLECULE = 3
MAX_ATTEMPTS_PER_MOLECULE = 30
SEED = 42


def main():
    Chem.SetUseLegacyStereoPerception(True)
    tmpRandom = random.Random(SEED)
    tmpRows = []
    tmpDiscarded = []
    tmpSupplier = Chem.SDMolSupplier(sys.argv[1])
    for tmpIndex, tmpMol in enumerate(tmpSupplier, start=1):
        if tmpMol is None:
            tmpRows.append("%d\t\t" % tmpIndex)
            continue
        tmpCanonicalSmiles = Chem.MolToSmiles(tmpMol)
        tmpWritings = []
        tmpAttempts = 0
        while len(tmpWritings) < WRITINGS_PER_MOLECULE and tmpAttempts < MAX_ATTEMPTS_PER_MOLECULE:
            tmpAttempts += 1
            tmpOrder = list(range(tmpMol.GetNumAtoms()))
            tmpRandom.shuffle(tmpOrder)
            tmpRenumbered = Chem.RenumberAtoms(tmpMol, tmpOrder)
            Chem.Kekulize(tmpRenumbered, clearAromaticFlags=True)
            tmpWriting = Chem.MolToSmiles(tmpRenumbered, canonical=False, kekuleSmiles=True)
            if Chem.MolToSmiles(Chem.MolFromSmiles(tmpWriting)) != tmpCanonicalSmiles:
                tmpDiscarded.append(tmpIndex)
                continue
            tmpWritings.append(tmpWriting)
        tmpRows.append("%d\t%s\t%s" % (tmpIndex, tmpCanonicalSmiles, " ".join(tmpWritings)))
    print("# generated by generate_biofacquim_stereo_reference.py with RDKit " + rdBase.rdkitVersion)
    print("# discarded writings that RDKit does not parse back to the same compound: %d (records %s)"
          % (len(tmpDiscarded), ",".join(str(tmpRecord) for tmpRecord in sorted(set(tmpDiscarded)))))
    print("record\trdkit_canonical_smiles\twritings")
    for tmpRow in tmpRows:
        print(tmpRow)


if __name__ == "__main__":
    main()
