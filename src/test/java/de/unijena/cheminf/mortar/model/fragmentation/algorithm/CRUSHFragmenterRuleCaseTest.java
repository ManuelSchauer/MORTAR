package de.unijena.cheminf.mortar.model.fragmentation.algorithm;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;

import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.Locale;
import java.util.Objects;

/**
 * Tests the cleavage steps of the {@link CRUSHFragmenter} with the hand-written test molecules of the individual CRUSH
 * rules (file CRUSH_Rule_Cases.tsv in the test resources, generated by CRUSH_Reference_Generator.py with the RDKit from
 * CRUSH_Rule_Cases_Input.tsv): per rule at least three molecules with a step of the rule and two without, and
 * molecules for ring bonds, protected atoms (fused, spiro, bridged, neighbours), the minimum fragment size, charges,
 * stereochemistry, salts, pseudo atoms, and the example data set of the authors. For every molecule and every rule, the
 * steps of the fragmenter (cleaved bonds and hydrogen-saturated products, with stereochemistry) must be identical to
 * the reference steps of the CRUSHFragmenter definition (part 2 of the generator), every valid step of the published
 * procedure (part 1, RunReactants semantics) must be among them with the same products, and the protected atoms must
 * be identical. The differences of part 1 that are deliberate (ring bonds, neutral aromatic nitrogen atoms, the ether
 * rule at heteroaromatic rings) are categories of the file, see {@link CRUSHFragmenter}.
 *
 * @author Manuel Schauer
 * @version 1.0.0.0
 */
public class CRUSHFragmenterRuleCaseTest {
    /**
     * Name of the file with the rule cases in the test resources.
     */
    private static final String RULE_CASES_FILE = "CRUSH_Rule_Cases.tsv";
    /**
     * Number of rule cases in the file.
     */
    private static final int RULE_CASES_COUNT = 238;
    //
    /**
     * Constructor that sets the default locale to British English, which is important for the correct functioning of the
     * fragmenter because the settings tooltips are imported from the message.properties file.
     */
    public CRUSHFragmenterRuleCaseTest() {
        Locale.setDefault(Locale.of("en", "GB"));
    }
    //
    /**
     * Compares the steps and protected atoms of all rule cases with the reference, which must match exactly, including
     * stereochemistry, and checks the expectation of every case (step of the tested rule or not).
     *
     * @throws Exception if anything goes wrong
     */
    @Test
    public void ruleCasesTest() throws Exception {
        CRUSHFragmenterReferenceTest.StepComparisonResult tmpResult;
        try (InputStream tmpStream = CRUSHFragmenterRuleCaseTest.class.getResourceAsStream(
                CRUSHFragmenterRuleCaseTest.RULE_CASES_FILE)) {
            Objects.requireNonNull(tmpStream, "Rule cases file not found.");
            tmpResult = CRUSHFragmenterReferenceTest.compareSteps(
                    new BufferedReader(new InputStreamReader(tmpStream, StandardCharsets.UTF_8)),
                    CRUSHFragmenterTest.createOriginalFragmenter(), Integer.MAX_VALUE);
        }
        System.out.println(tmpResult.summary());
        Assertions.assertEquals(CRUSHFragmenterRuleCaseTest.RULE_CASES_COUNT, tmpResult.molecules());
        Assertions.assertEquals(0, tmpResult.skipped(), tmpResult.report());
        Assertions.assertEquals(0, tmpResult.mismatches(), tmpResult.report());
        Assertions.assertEquals(0, tmpResult.stereoMismatches(), tmpResult.report());
        Assertions.assertEquals(0, tmpResult.originalMismatches(), tmpResult.report());
        Assertions.assertEquals(0, tmpResult.protectedAtomMismatches(), tmpResult.report());
        Assertions.assertEquals(0, tmpResult.expectationMismatches(), tmpResult.report());
    }
}
